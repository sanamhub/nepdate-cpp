// Pairs "00" to "99" per line of the digit table.
constexpr int kPairsPerLine = 25;

// Zero-padded digits. Not std::format: libstdc++ 12, the GCC floor, has no <format>.
std::string digits(std::uint32_t value, std::uint32_t base, std::size_t width) {
    constexpr std::string_view kDigits = "0123456789ABCDEF";
    std::string out;
    while (value != 0 || out.size() < width) {
        out.insert(out.begin(), kDigits[value % base]);
        value /= base;
    }
    return out;
}

// A C string literal for text: printable ASCII as is, every other byte as a three-digit octal
// escape, which can't swallow the character after it (ADR-0001 section 6).
std::string literal(std::string_view text) {
    std::string out = "\"";
    for (const char c : text) {
        const auto byte = static_cast<unsigned char>(c);
        if (byte >= 0x20U && byte < 0x7FU && c != '"' && c != '\\') {
            out += c;
        } else {
            out += "\\" + digits(byte, 8U, 3U);
        }
    }
    out += '"';
    return out;
}

// "U+0938 U+093E" for non-ASCII text, so the ASCII header still says what the escapes are.
// Empty for ASCII text, which the literal shows already.
std::string code_points(std::string_view text) {
    std::string out;
    std::size_t i = 0;
    bool non_ascii = false;
    while (i < text.size()) {
        const auto lead = static_cast<unsigned char>(text[i]);
        std::uint32_t cp = lead;
        std::size_t extra = 0;
        if (lead >= 0xF0U) {
            cp = lead & 0x07U;
            extra = 3;
        } else if (lead >= 0xE0U) {
            cp = lead & 0x0FU;
            extra = 2;
        } else if (lead >= 0xC0U) {
            cp = lead & 0x1FU;
            extra = 1;
        }
        for (std::size_t k = 1; k <= extra && i + k < text.size(); ++k) {
            cp = cp << 6U | (static_cast<unsigned char>(text[i + k]) & 0x3FU);
        }
        non_ascii = non_ascii || extra > 0;
        i += extra + 1;
        if (!out.empty()) {
            out += ' ';
        }
        out += "U+" + digits(cp, 16U, 4U);
    }
    return non_ascii ? out : std::string{};
}

// One entry line: the literal, then a comment with the code points and an English gloss.
std::string entry(std::string_view text, std::string_view gloss) {
    std::string line = "    " + literal(text) + ",";
    const std::string cps = code_points(text);
    if (!cps.empty()) {
        line += " // " + cps + " (" + std::string(gloss) + ")";
    }
    return line + "\n";
}

template <std::size_t N>
std::string name_array(std::string_view comment, std::string_view name,
                       const std::array<std::string_view, N>& values,
                       const std::array<std::string_view, N>& glosses) {
    std::string out = "// " + std::string(comment) + "\n";
    out += "inline constexpr std::array<std::string_view, " + std::to_string(N) + "> " +
           std::string(name) + " = {\n";
    for (std::size_t i = 0; i < N; ++i) {
        out += entry(values.at(i), glosses.at(i));
    }
    return out + "};\n\n";
}

// The spellings of one PARSING section 3 row, in order, without duplicates.
std::vector<std::string_view> spellings(std::string_view row) {
    std::vector<std::string_view> out;
    std::size_t start = 0;
    while (start <= row.size()) {
        std::size_t end = row.find(", ", start);
        if (end == std::string_view::npos) {
            end = row.size();
        }
        const std::string_view word = row.substr(start, end - start);
        if (std::find(out.begin(), out.end(), word) == out.end()) {
            out.push_back(word);
        }
        start = end + 2;
    }
    return out;
}

