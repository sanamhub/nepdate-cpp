std::string render_names_tables() {
    std::string out;
    out += "// Generated by tools/codegen from tools/codegen/names.hpp. DO NOT EDIT.\n";
    out +=
        "// Names of FORMATTING section 1 and the words of PARSING sections 2 and 3. Devanagari\n";
    out +=
        "// is written as octal escapes with its code points in a comment (ADR-0001 section 6).\n";
    out += "// Regenerate with the codegen target.\n";
    out += "#ifndef NEPDATE_DETAIL_NAMES_TABLES_HPP\n";
    out += "#define NEPDATE_DETAIL_NAMES_TABLES_HPP\n";
    out += "\n";
    out += "#include <array>\n";
    out += "#include <cstdint>\n";
    out += "#include <string_view>\n";
    out += "\n";
    out += "namespace nepdate::detail {\n";
    out += "\n";

    out +=
        "// The two ASCII digits of 0 to 99: number n is kDigitPairs[2n], kDigitPairs[2n + 1].\n";
    out += "inline constexpr std::string_view kDigitPairs =\n";
    for (int n = 0; n < 100; ++n) {
        if (n % kPairsPerLine == 0) {
            out += "    \"";
        }
        out += static_cast<char>('0' + n / 10);
        out += static_cast<char>('0' + n % 10);
        if (n % kPairsPerLine == kPairsPerLine - 1) {
            out += n == 99 ? "\";\n" : "\"\n";
        }
    }
    out += "\n";

    out += name_array("Month names in English, Baishakh first.", "kMonthNameEn", kMonthNamesEn,
                      kMonthNamesEn);
    out += name_array("Three-letter English month names (D-04: Asa and Aso).", "kMonthShortEn",
                      kMonthShortEn, kMonthNamesEn);
    out += name_array("Month names in Nepali; Nepali has no short form.", "kMonthNameNe",
                      kMonthNamesNe, kMonthNamesEn);
    out += name_array("Weekday names in English, Sunday first.", "kWeekdayNameEn", kWeekdayNamesEn,
                      kWeekdayNamesEn);
    out += name_array("Short English weekday names.", "kWeekdayShortEn", kWeekdayShortEn,
                      kWeekdayNamesEn);
    out +=
        name_array("Weekday names in Nepali.", "kWeekdayNameNe", kWeekdayNamesNe, kWeekdayNamesEn);
    out += name_array("Short Nepali weekday names.", "kWeekdayShortNe", kWeekdayShortNe,
                      kWeekdayNamesEn);

    std::vector<std::pair<std::string_view, int>> all;
    for (std::size_t m = 0; m < kMonthSpellingRows.size(); ++m) {
        for (const std::string_view word : spellings(kMonthSpellingRows.at(m))) {
            all.emplace_back(word, static_cast<int>(m) + 1);
        }
    }
    out += "// A month spelling lenient parsing accepts (PARSING section 3). Latin spellings are "
           "lower\n";
    out += "// case and compare case-insensitively; Devanagari ones compare byte for byte.\n";
    out += "struct month_spelling {\n";
    out += "    std::string_view text;\n";
    out += "    std::uint8_t month;\n";
    out += "};\n";
    out += "\n";
    out += "inline constexpr std::array<month_spelling, " + std::to_string(all.size()) +
           "> kMonthSpellings = {{\n";
    for (const auto& [word, month] : all) {
        std::string line = "    {" + literal(word) + ", " + std::to_string(month) + "},";
        const std::string cps = code_points(word);
        if (!cps.empty()) {
            line += " // " + cps;
        }
        out += line + "\n";
    }
    out += "}};\n";
    out += "\n";

    const std::array<std::string_view, 10> era_gloss = {
        "BS", "B.S.", "B.S", "VS", "V.S.", "V.S", "bi.sam.", "vi.sam.", "bi.sam", "vi.sam",
    };
    out +=
        name_array("Era markers lenient parsing drops (PARSING section 2); Latin ones lower case.",
                   "kEraMarkers", kEraMarkers, era_gloss);
    const std::array<std::string_view, 2> dropped_gloss = {"gate", "miti"};
    out += name_array("Other words lenient parsing drops (PARSING section 2).", "kDroppedWords",
                      kDroppedWords, dropped_gloss);

    out += "} // namespace nepdate::detail\n";
    out += "\n";
    out += "#endif // NEPDATE_DETAIL_NAMES_TABLES_HPP\n";
    return out;
}

